"""Коды HoldingReg[11], назначенные в программе ПЛК.

Это внутренние коды проекта 1..19, а не HEX-коды
истории аварий из регистров частотника 0090h..0092h.
"""

ALARMS = {
    0: ("", "Нет ошибок"),
    1: ("UV1", "Низкое напряжение ЗПТ"),
    2: ("UV3", "Нет сигнала окончания предзаряда"),
    3: ("SC", "Короткое замыкание"),
    4: ("OC", "Перегрузка по току"),
    5: ("OV", "Высокое напряжение ЗПТ"),
    6: ("OH", "Перегрев радиатора"),
    7: ("OL1", "Перегрузка двигателя"),
    8: ("OL2", "Перегрузка преобразователя"),
    9: ("CPF03", "Ошибка EEPROM"),
    10: ("STOP-UV", "Низкое напряжение ЗПТ в режиме СТОП"),
    11: ("STOP-OV", "Высокое напряжение ЗПТ в режиме СТОП"),
    12: ("STOP-OH", "Перегрев радиатора в режиме СТОП"),
    13: ("b.b.", "Внешняя блокировка"),
    14: ("CTER", "Ошибка измерителя тока"),
    15: ("FBL", "Потеря обратной связи ПИД"),
    16: ("E.S.", "Внешний аварийный останов"),
    17: ("STP0", "Нулевое задание частоты"),
    18: ("STP1", "Запрет пуска"),
    19: ("STP2", "Стоп с пульта управления"),
}


def alarm_text(code):
    """Полное описание для журнала и сообщений."""
    code = int(code)
    entry = ALARMS.get(code)

    if entry is None:
        return f"Неизвестный код {code}"

    symbol, description = entry
    return f"{symbol}: {description}" if symbol else description


def alarm_symbol(code):
    """Короткое обозначение для карточки."""
    code = int(code)

    if code == 0:
        return "нет"

    entry = ALARMS.get(code)
    return entry[0] if entry else f"код {code}"